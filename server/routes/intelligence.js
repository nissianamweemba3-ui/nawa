// Phase Three intelligence routes (tenant side): assistant, copilot, document intelligence, insights,
// executive summary, regulatory notifications.
import { newId } from '../lib/crypto.js';
import { nowIso } from '../db.js';
import { audit } from '../lib/audit.js';
import { badRequest, notFound, str, oneOf, reply } from '../lib/http.js';
import { requireOrgPermission } from '../auth/rbac.js';
import { TenantRepo } from '../tenancy.js';
import { listControls } from '../kb/store.js';
import { extractText, SUPPORTED_TYPES } from '../lib/extract.js';
import { copilotGuide, addDays } from '../intel/copilot.js';
import { analyseDocument, CHECKLISTS } from '../intel/documents.js';
import { computeInsights, executiveSummary } from '../intel/insights.js';
import { requireAuth } from './auth.js';
import { createTask } from './compliance.js';

function formatAnalysis(a) {
  return { id: a.id, evidenceId: a.evidence_id, checklist: a.checklist, checklistLabel: CHECKLISTS[a.checklist]?.label ?? a.checklist,
    findings: JSON.parse(a.findings_json), securityFlags: JSON.parse(a.security_flags_json), aiUsed: Boolean(a.ai_used),
    createdBy: a.created_by, createdAt: a.created_at };
}

export function registerIntelligenceRoutes(r, svc) {
  const { db, store, index, gateway, assistant } = svc;
  const auth = (ctx, perm) => { requireAuth(ctx); requireOrgPermission(ctx, perm); return new TenantRepo(db, ctx.orgId); };

  r.get('/api/ai/status', ({ ctx }) => {
    requireAuth(ctx);
    return { provider: gateway.providerName, live: gateway.provider.live,
      note: gateway.provider.live ? 'Answers are generated by the configured model, grounded in approved sources and validated.'
        : 'No model is configured: AI features run in deterministic, source-quoting mode. Set ANTHROPIC_API_KEY to enable model generation.' };
  });

  // ---- AI Compliance Assistant ----
  r.post('/api/assistant/ask', async ({ ctx, body }) => {
    requireAuth(ctx);
    const question = str(body, 'question', { max: svc.config.ai.maxQuestionChars, min: 3 });
    const controlId = str(body, 'controlId', { required: false, max: 64 });
    const out = await assistant.ask(ctx, { question, controlId });
    return {
      blocked: out.blocked, mode: out.mode, provider: out.provider, interactionId: out.interactionId,
      answer: out.result.answer, confidence: out.result.confidence, insufficientSources: out.result.insufficientSources,
      citations: out.result.citations, sources: out.sources ?? [], retrieved: out.retrieved ?? [], flags: out.flags,
    };
  });

  // ---- Compliance Copilot ----
  r.get('/api/copilot/:controlId', ({ ctx, params }) => copilotGuide(db, auth(ctx, 'assessment.read'), index, params.controlId));

  r.post('/api/copilot/:controlId/accept-task', ({ ctx, params }) => {
    const repo = auth(ctx, 'task.create');
    const guide = copilotGuide(db, repo, index, params.controlId);
    if (!guide.suggestedTask) throw badRequest('There is no suggested task for this control');
    const t = guide.suggestedTask;
    return reply(201, createTask(db, ctx, { title: t.title, description: t.description, controlId: t.controlId,
      priority: t.priority, dueDate: t.dueDate, source: 'copilot' }));
  });

  // ---- Document Intelligence ----
  r.get('/api/documents/checklists', ({ ctx }) => {
    auth(ctx, 'evidence.read');
    return { checklists: Object.entries(CHECKLISTS).map(([key, c]) => ({ key, label: c.label, controlId: c.controlId, items: c.items.map(([id, label]) => ({ id, label })) })),
      analysableTypes: Object.keys(SUPPORTED_TYPES) };
  });

  r.post('/api/documents/analyse', async ({ ctx, body }) => {
    const repo = auth(ctx, 'document.analyse');
    const evidenceId = str(body, 'evidenceId', { max: 64 });
    const checklist = oneOf(body, 'checklist', Object.keys(CHECKLISTS));
    const e = repo.get('evidence', evidenceId); // permission + tenant validation: only this organisation's evidence
    if (!e) throw notFound('Evidence not found');
    if (!SUPPORTED_TYPES[e.mime]) throw badRequest(`This file type cannot be analysed (${e.mime}). Supported: ${Object.keys(SUPPORTED_TYPES).join(', ')}`);
    let text;
    try { text = extractText(e.mime, store.get(ctx.orgId, e.storage_key)); } catch (err) { throw badRequest(`Could not extract text: ${err.message}`); }
    if (!text.trim()) throw badRequest('No text could be extracted from this document');
    const out = await analyseDocument({ gateway, ctx, checklistKey: checklist, text, filename: e.filename });
    const row = repo.insert('doc_analyses', { id: newId(), evidence_id: e.id, checklist, findings_json: JSON.stringify(out.findings),
      security_flags_json: JSON.stringify(out.securityFlags), ai_used: out.aiUsed ? 1 : 0, created_by: ctx.userId, created_at: nowIso() });
    audit(db, { orgId: ctx.orgId, userId: ctx.userId, action: 'document.analyse', target: row.id,
      metadata: { evidenceId: e.id, checklist, gaps: out.findings.filter((f) => f.status !== 'covered').length, securityFlags: out.securityFlags.map((f) => f.id) } });
    return reply(201, { ...formatAnalysis(row), mode: out.mode, gatewayFlags: out.gatewayFlags });
  });

  r.get('/api/documents/analyses', ({ ctx }) => auth(ctx, 'evidence.read').list('doc_analyses').map(formatAnalysis));

  r.get('/api/documents/analyses/:id', ({ ctx, params }) => {
    const a = auth(ctx, 'evidence.read').get('doc_analyses', params.id);
    if (!a) throw notFound('Analysis not found');
    return formatAnalysis(a);
  });

  // Human review of AI/rule findings. Accepting creates a remediation task — the only way findings become actions.
  r.post('/api/documents/analyses/:id/findings/:findingId/review', ({ ctx, params, body }) => {
    const repo = auth(ctx, 'finding.review');
    const a = repo.get('doc_analyses', params.id);
    if (!a) throw notFound('Analysis not found');
    const findings = JSON.parse(a.findings_json);
    const f = findings.find((x) => x.id === params.findingId);
    if (!f) throw notFound('Finding not found');
    if (f.review.status !== 'pending') throw badRequest(`Finding review is ${f.review.status}`);
    const decision = oneOf(body, 'decision', ['accept', 'dismiss']);
    const note = str(body, 'note', { required: false, max: 1000 });
    let task = null;
    if (decision === 'accept') {
      const priority = listControls(db).find((c) => c.id === f.controlId)?.priority ?? 'medium';
      task = createTask(db, ctx, { title: `Document review: ${f.label}`, description: `${f.observation}${note ? `\nReviewer note: ${note}` : ''}`,
        controlId: f.controlId, priority, dueDate: addDays(priority === 'high' ? 14 : 30), source: 'document_ai' });
    }
    f.review = { status: decision === 'accept' ? 'accepted' : 'dismissed', by: ctx.userId, at: nowIso(), taskId: task?.id ?? null, note };
    repo.update('doc_analyses', a.id, { findings_json: JSON.stringify(findings) });
    audit(db, { orgId: ctx.orgId, userId: ctx.userId, action: 'finding.review', target: `${a.id}/${f.id}`, metadata: { decision, taskId: task?.id ?? null } });
    return { finding: f, task };
  });

  // ---- Risk insights & executive intelligence ----
  r.get('/api/insights', ({ ctx }) => computeInsights(db, auth(ctx, 'insights.read')));

  r.post('/api/insights/executive-summary', async ({ ctx }) => {
    const repo = auth(ctx, 'insights.executive');
    const out = await executiveSummary(db, repo, gateway, ctx);
    return { summary: out.result.summary, keyRisks: out.result.keyRisks, facts: out.facts, mode: out.mode, provider: out.provider, flags: out.flags };
  });

  // ---- Regulatory notifications (tenant side) ----
  r.get('/api/regulatory/notifications', ({ ctx }) => {
    const repo = auth(ctx, 'regulatory.read');
    return repo.list('reg_notifications').map((n) => {
      const c = db.prepare('SELECT id, title, significance, reviewed_at, new_version_id, source_id, review_note FROM reg_changes WHERE id = ?').get(n.change_id);
      return { id: n.id, status: n.status, affectedControls: JSON.parse(n.affected_controls_json), createdAt: n.created_at,
        acknowledgedAt: n.acknowledged_at, change: c ? { id: c.id, title: c.title, significance: c.significance, reviewedAt: c.reviewed_at,
          sourceId: c.source_id, newVersionId: c.new_version_id, reviewNote: c.review_note } : null };
    });
  });

  r.post('/api/regulatory/notifications/:id/acknowledge', ({ ctx, params, body }) => {
    const repo = auth(ctx, 'regulatory.acknowledge');
    const n = repo.get('reg_notifications', params.id);
    if (!n) throw notFound('Notification not found');
    if (n.status !== 'open') throw badRequest('Notification already acknowledged');
    const tasks = [];
    if (body.createTasks === true) {
      const change = db.prepare('SELECT title FROM reg_changes WHERE id = ?').get(n.change_id);
      const controls = listControls(db);
      for (const cid of JSON.parse(n.affected_controls_json)) {
        const c = controls.find((x) => x.id === cid);
        tasks.push(createTask(db, ctx, { title: `Review after regulatory update: ${c.requirementTitle}`,
          description: `A reviewed regulatory update ("${change.title}") may affect this control. Review the control and its evidence.`,
          controlId: cid, priority: c.priority, dueDate: addDays(30), source: 'regulatory' }));
      }
    }
    repo.update('reg_notifications', n.id, { status: 'acknowledged', acknowledged_by: ctx.userId, acknowledged_at: nowIso() });
    audit(db, { orgId: ctx.orgId, userId: ctx.userId, action: 'regulatory.acknowledge', target: n.id, metadata: { tasks: tasks.length } });
    return { ok: true, tasks };
  });
}
